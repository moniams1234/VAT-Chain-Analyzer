def is_eu_country(country_code: str) -> bool:
    return country_code in EU_COUNTRIES


def get_country_name(country_code: str) -> str:
    return ALL_COUNTRIES.get(country_code, country_code)


def get_sorted_countries():
    """Returns sorted list of (code, name) tuples — Poland first."""
    sorted_list = sorted(ALL_COUNTRIES.items(), key=lambda x: x[1])
    pl = [("PL", "Polska")]
    rest = [(k, v) for k, v in sorted_list if k != "PL"]
    return pl + rest
